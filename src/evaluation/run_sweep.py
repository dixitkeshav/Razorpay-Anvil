"""`make sweep` entrypoint — Phase 13. Sensitivity sweep over
docs/OUTCOME-MODEL.md's assumed outcome-model parameters:
p_retry_success x p_reroute_success x cost_reroute, 48 cells. Writes
docs/SENSITIVITY.md. Every cell comes from an actual `replay()` run
against the held-out set with that cell's parameters — see CLAUDE.md
rule #1.

Detection/attribution/impact never depend on these parameters (they
don't touch money), so the set of incidents found is identical across
every cell — only the policy engine's EV ranking and the execution
simulator's outcome draw change, which is exactly what this sweep is
meant to isolate.
"""

from src.evaluation.replay import replay
from src.generator.engine import HOLDOUT_START_EPOCH
from src.generator.seed import DEFAULT_SIM_MINUTES, HOLDOUT_SEED, generate
from src.ingest.db import connect, register_events
from src.policy import config as policy_config

RETRY_GRID = [0.35, 0.45, 0.55, 0.65]
REROUTE_GRID = [0.50, 0.60, 0.70, 0.80]
COST_GRID_PAISE = [2_000, 5_000, 10_000]  # Rs. 20, 50, 100

SENSITIVITY_PATH = "docs/SENSITIVITY.md"


def run_sweep(con, seed: int) -> list[dict]:
    original = (
        policy_config.P_RETRY_SUCCESS,
        policy_config.P_REROUTE_SUCCESS,
        policy_config.COST_REROUTE_PAISE,
    )
    results = []
    try:
        for p_retry in RETRY_GRID:
            for p_reroute in REROUTE_GRID:
                for cost in COST_GRID_PAISE:
                    policy_config.P_RETRY_SUCCESS = p_retry
                    policy_config.P_REROUTE_SUCCESS = p_reroute
                    policy_config.COST_REROUTE_PAISE = cost
                    sc = replay(con, seed=seed)
                    results.append(
                        {
                            "p_retry_success": p_retry,
                            "p_reroute_success": p_reroute,
                            "cost_reroute_paise": cost,
                            "net_incremental_recovery_paise": sc[
                                "net_incremental_recovery_paise"
                            ],
                        }
                    )
    finally:
        (
            policy_config.P_RETRY_SUCCESS,
            policy_config.P_REROUTE_SUCCESS,
            policy_config.COST_REROUTE_PAISE,
        ) = original
    return results


def render_sensitivity_md(results: list[dict], seed: int) -> str:
    from datetime import UTC, datetime

    generated_at = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    positive = sum(1 for r in results if r["net_incremental_recovery_paise"] > 0)
    negative = [r for r in results if r["net_incremental_recovery_paise"] <= 0]

    lines = [
        "# Sensitivity — GENERATED, do not hand-edit",
        "",
        f"Generated by `make sweep` at {generated_at}, from the held-out set "
        f"(seed={seed}). 48 cells: p_retry_success x p_reroute_success x "
        "cost_reroute. Every cell is a full `src.evaluation.replay.replay()` "
        "run with that cell's parameters substituted into "
        "`src.policy.config` — not an interpolation or a formula. See "
        "CLAUDE.md rule #1 and docs/OUTCOME-MODEL.md §6.",
        "",
        f"**Net incremental recovery is positive in {positive} of {len(results)} "
        f"parameter settings.**",
        "",
    ]

    for cost in COST_GRID_PAISE:
        lines.append(f"## cost_reroute = Rs. {cost / 100:.0f}")
        lines.append("")
        header = "| p_retry_success \\ p_reroute_success | " + " | ".join(
            f"{p:.2f}" for p in REROUTE_GRID
        ) + " |"
        lines.append(header)
        lines.append("|" + "---|" * (len(REROUTE_GRID) + 1))
        for p_retry in RETRY_GRID:
            row = [f"{p_retry:.2f}"]
            for p_reroute in REROUTE_GRID:
                cell = next(
                    r
                    for r in results
                    if r["p_retry_success"] == p_retry
                    and r["p_reroute_success"] == p_reroute
                    and r["cost_reroute_paise"] == cost
                )
                rupees = cell["net_incremental_recovery_paise"] / 100
                marker = " **[LOSS]**" if rupees <= 0 else ""
                row.append(f"Rs. {rupees:,.0f}{marker}")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

    lines += [
        "## Where Anvil loses money",
        "",
    ]
    if negative:
        lines.append(
            f"{len(negative)} of {len(results)} cells have net incremental "
            "recovery at or below zero:"
        )
        lines.append("")
        lines.append("| p_retry_success | p_reroute_success | cost_reroute | Net |")
        lines.append("|---|---|---|---|")
        for r in sorted(negative, key=lambda r: r["net_incremental_recovery_paise"]):
            lines.append(
                f"| {r['p_retry_success']:.2f} | {r['p_reroute_success']:.2f} | "
                f"Rs. {r['cost_reroute_paise'] / 100:.0f} | "
                f"Rs. {r['net_incremental_recovery_paise'] / 100:,.0f} |"
            )
    else:
        lines.append(
            "No cell in this grid goes negative on this held-out draw — the "
            "worst cell is still positive. See the full grid above for how "
            "close the worst cells come to zero."
        )

    return "\n".join(lines) + "\n"


def main() -> None:
    print(f"generating held-out set (seed={HOLDOUT_SEED}, minutes={DEFAULT_SIM_MINUTES})...")
    events_df, _ = generate(
        seed=HOLDOUT_SEED, sim_minutes=DEFAULT_SIM_MINUTES, start_epoch=HOLDOUT_START_EPOCH
    )
    con = connect()
    register_events(con, events_df)

    total_cells = len(RETRY_GRID) * len(REROUTE_GRID) * len(COST_GRID_PAISE)
    print(f"running {total_cells}-cell sensitivity sweep (this re-runs replay per cell)...")
    results = run_sweep(con, seed=HOLDOUT_SEED)

    print("writing", SENSITIVITY_PATH)
    content = render_sensitivity_md(results, seed=HOLDOUT_SEED)
    with open(SENSITIVITY_PATH, "w") as f:
        f.write(content)

    positive = sum(1 for r in results if r["net_incremental_recovery_paise"] > 0)
    print(f"net incremental recovery positive in {positive}/{len(results)} cells")


if __name__ == "__main__":
    main()
