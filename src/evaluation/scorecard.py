"""Formats a replay scorecard (src.evaluation.replay.replay's return
value) as the docs/RESULTS.md markdown table. Every number here is read
straight off the scorecard dict — nothing is computed or typed in this
module. See CLAUDE.md rule #1.
"""

from datetime import UTC, datetime


def _paise_to_rupees_str(paise: int) -> str:
    rupees = paise / 100
    return f"Rs. {rupees:,.2f}"


def render_results_md(scorecard: dict, seed: int, sim_minutes: int) -> str:
    generated_at = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    action_counts = scorecard["decisions_by_action"]

    lines = [
        "# Results — GENERATED, do not hand-edit",
        "",
        f"Generated by `make eval` at {generated_at}, from seed={seed}, "
        f"{sim_minutes} simulated minutes. Every number below is read "
        "directly from `src.evaluation.replay.replay()`'s return value — "
        "see CLAUDE.md rule #1.",
        "",
        "## Scorecard",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Incidents detected (L1) | {scorecard['incidents_detected']} |",
        f"| Failed attempts replayed | {scorecard['attempts_replayed']} |",
        f"| Automated actions taken (RETRY + REROUTE) | {scorecard['automated_action_count']} |",
        f"| RETRY decisions | {action_counts['RETRY']} |",
        f"| REROUTE decisions | {action_counts['REROUTE']} |",
        f"| HOLD decisions | {action_counts['HOLD']} |",
        f"| ESCALATE_HUMAN decisions | {action_counts['ESCALATE_HUMAN']} |",
        f"| Recovered attempts (simulated success) | {scorecard['recovered_count']} |",
        f"| Ledger entries written | {scorecard['ledger_entry_count']} |",
        "",
        "## Money recovered — agent-on vs agent-off",
        "",
        "Agent-off is the do-nothing baseline (docs/OUTCOME-MODEL.md §5): "
        "every one of these failed attempts simply stays failed. Agent-on "
        "is Anvil's policy engine acting on each one.",
        "",
        "| | Agent-off | Agent-on |",
        "|---|---|---|",
        f"| GMV recovered | {_paise_to_rupees_str(scorecard['gmv_recovered_agent_off_paise'])} "
        f"| {_paise_to_rupees_str(scorecard['gmv_recovered_agent_on_paise'])} |",
        "",
        f"**Execution cost:** {_paise_to_rupees_str(scorecard['execution_cost_paise'])}"
        " (REROUTE cost, docs/OUTCOME-MODEL.md §3)",
        "",
        f"**Net incremental recovery: "
        f"{_paise_to_rupees_str(scorecard['net_incremental_recovery_paise'])}**",
        "",
        "## How this meets Track 03 bar item 4 (measured money recovered)",
        "",
        "The net incremental recovery figure above is the batch-level "
        "measured-money-recovered evidence: agent-on GMV recovered minus "
        "agent-off GMV recovered (always Rs. 0.00, by the do-nothing "
        "definition) minus execution cost, over every failed attempt "
        "inside every incident this run's detector found.",
        "",
        "## Escalation and stopping-rule evidence (bar items 5 and 6)",
        "",
        "| Escalation reason (bucketed) | Count |",
        "|---|---|",
    ]
    if scorecard["escalation_reasons_count"]:
        for reason, count in sorted(scorecard["escalation_reasons_count"].items()):
            lines.append(f"| {reason} | {count} |")
    else:
        lines.append("| (none fired this run) | 0 |")

    lines += [
        "",
        "| Hold reason (bucketed) | Count |",
        "|---|---|",
    ]
    if scorecard["hold_reasons_count"]:
        for reason, count in sorted(scorecard["hold_reasons_count"].items()):
            lines.append(f"| {reason} | {count} |")
    else:
        lines.append("| (none fired this run) | 0 |")

    lines += [
        "",
        "## What this evaluation cannot tell you",
        "",
        "- **Only the currently-tuned detector's easy-tier recall is "
        "reflected here.** `h=15` (docs/JOURNAL.md Phase 3) was tuned for "
        "zero false alarms and catches the easy-tier episode reliably, "
        "but Medium/Hard-tier episodes (C, D, E, F, G) are not "
        "necessarily represented in this batch's detected-incident count "
        "— full stratified recall per tier is a Phase 13 held-out-set "
        "evaluation, not this one.",
        "- **This is the main seed, not the held-out set.** Headline "
        "recall/precision claims belong on held-out data (Phase 13); this "
        "scorecard demonstrates the counterfactual-replay mechanism "
        "end-to-end and gives a real, reproducible rupee figure from the "
        "committed seed, not a generalization claim.",
        "- **The outcome model's success probabilities are stated "
        "assumptions, not measured ones** — see docs/OUTCOME-MODEL.md and "
        "the Phase 13 sensitivity sweep (docs/SENSITIVITY.md) for the "
        "range this figure moves across.",
        "- **Agent-off recovers exactly Rs. 0.00 by construction**, since "
        "the generator does not model an independent, un-assisted retry "
        "behavior (docs/OUTCOME-MODEL.md §5) — the net incremental figure "
        "above is therefore equal to agent-on's own recovery minus cost, "
        "not a comparison against a competing baseline strategy.",
    ]
    if not scorecard["escalation_reasons_count"] and not scorecard["hold_reasons_count"]:
        lines.append(
            "- **No guardrail fired in this run.** This is a real "
            "characteristic of this specific batch (one easy-tier "
            "incident, moderate amounts, confidence above threshold, and "
            "the incident's own aggregate never reached SEVERE), not a "
            "rendering gap — the zero counts above are genuine. See "
            "docs/JOURNAL.md."
        )

    return "\n".join(lines) + "\n"
