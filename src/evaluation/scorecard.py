"""Formats a replay scorecard (src.evaluation.replay.replay's return
value) and a recall report (src.evaluation.recall.evaluate_recall's
return value) as the docs/RESULTS.md markdown. Every number here is read
straight off those dicts — nothing is computed or typed in this module.
See CLAUDE.md rule #1.
"""

from datetime import UTC, datetime


def _paise_to_rupees_str(paise: int) -> str:
    rupees = paise / 100
    return f"Rs. {rupees:,.2f}"


def render_results_md(scorecard: dict, recall: dict, seed: int, sim_minutes: int) -> str:
    generated_at = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    action_counts = scorecard["decisions_by_action"]

    lines = [
        "# Results — GENERATED, do not hand-edit",
        "",
        f"Generated by `make eval` at {generated_at}, from the **held-out set** "
        f"(seed={seed}, {sim_minutes} simulated minutes — fresh seed, redrawn "
        "episode timing, never used to tune the detector or attribution; see "
        "docs/EPISODE-SPEC.md §7). Every number below is read directly from "
        "`src.evaluation.replay.replay()` and `src.evaluation.recall.evaluate_recall()`'s "
        "return values — see CLAUDE.md rule #1.",
        "",
        "## Stratified recall by difficulty tier",
        "",
        "| Tier | Episodes | Detected | Recall |",
        "|---|---|---|---|",
    ]
    for tier in ["easy", "medium", "hard"]:
        stats = recall["recall_by_tier"].get(tier)
        if stats is None:
            continue
        pct = f"{100 * stats['detected'] / stats['total']:.0f}%" if stats["total"] else "n/a"
        lines.append(f"| {tier} | {stats['total']} | {stats['detected']} | {pct} |")

    lines += [
        "",
        f"**Decoys:** {recall['decoys_testable']} of {recall['decoys_total']} decoy episodes "
        "have a slice dimension the lattice actually tests (see "
        "src.evaluation.recall.TESTABLE_DECOY_DIMS); "
        f"**{recall['decoys_falsely_flagged']} of those were falsely flagged** as incidents. "
        "This is the most informative number in this document — see "
        "'What this evaluation cannot tell you' below.",
        "",
        "## Scorecard (counterfactual replay)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Incidents detected (L1) | {scorecard['incidents_detected']} |",
        f"| Failed attempts replayed | {scorecard['attempts_replayed']} |",
        f"| Automated actions taken (RETRY + REROUTE) | {scorecard['automated_action_count']} |",
        f"| RETRY decisions | {action_counts['RETRY']} |",
        f"| REROUTE decisions | {action_counts['REROUTE']} |",
        f"| HOLD decisions | {action_counts['HOLD']} |",
        f"| ESCALATE_HUMAN decisions | {action_counts['ESCALATE_HUMAN']} |",
        f"| Recovered attempts (simulated success) | {scorecard['recovered_count']} |",
        f"| Ledger entries written | {scorecard['ledger_entry_count']} |",
        "",
        "## Money recovered — agent-on vs agent-off",
        "",
        "Agent-off is the do-nothing baseline (docs/OUTCOME-MODEL.md §5): "
        "every one of these failed attempts simply stays failed. Agent-on "
        "is Anvil's policy engine acting on each one.",
        "",
        "| | Agent-off | Agent-on |",
        "|---|---|---|",
        f"| GMV recovered | {_paise_to_rupees_str(scorecard['gmv_recovered_agent_off_paise'])} "
        f"| {_paise_to_rupees_str(scorecard['gmv_recovered_agent_on_paise'])} |",
        "",
        f"**Execution cost:** {_paise_to_rupees_str(scorecard['execution_cost_paise'])}"
        " (REROUTE cost, docs/OUTCOME-MODEL.md §3)",
        "",
        f"**Net incremental recovery: "
        f"{_paise_to_rupees_str(scorecard['net_incremental_recovery_paise'])}**",
        "",
        "See docs/SENSITIVITY.md for how this figure moves across the outcome "
        "model's parameter grid, including where it goes negative.",
        "",
        "## How this meets Track 03 bar item 4 (measured money recovered)",
        "",
        "The net incremental recovery figure above is the batch-level "
        "measured-money-recovered evidence: agent-on GMV recovered minus "
        "agent-off GMV recovered (always Rs. 0.00, by the do-nothing "
        "definition) minus execution cost, over every failed attempt "
        "inside every incident this run's detector found, on held-out data.",
        "",
        "## Escalation and stopping-rule evidence (bar items 5 and 6)",
        "",
        "| Escalation reason (bucketed) | Count |",
        "|---|---|",
    ]
    if scorecard["escalation_reasons_count"]:
        for reason, count in sorted(scorecard["escalation_reasons_count"].items()):
            lines.append(f"| {reason} | {count} |")
    else:
        lines.append("| (none fired this run) | 0 |")

    lines += [
        "",
        "| Hold reason (bucketed) | Count |",
        "|---|---|",
    ]
    if scorecard["hold_reasons_count"]:
        for reason, count in sorted(scorecard["hold_reasons_count"].items()):
            lines.append(f"| {reason} | {count} |")
    else:
        lines.append("| (none fired this run) | 0 |")

    lines += [
        "",
        "## Failure taxonomy",
        "",
        "Read directly off the per-episode table this run scored against "
        "held-out ground truth:",
        "",
        "| Episode | Tier | Detected |",
        "|---|---|---|",
    ]
    for ep in recall["per_episode"]:
        if ep["detected"]:
            marker = "yes"
        elif not ep["testable"]:
            marker = "n/a (untestable slice)"
        else:
            marker = "no"
        lines.append(f"| {ep['episode_id']} | {ep['tier']} | {marker} |")

    lines += [
        "",
        "The pattern is consistent with Phase 3's own tuning finding, not a "
        "new surprise: `h=15` was chosen specifically to hold false alarms "
        "at zero (docs/JOURNAL.md Phase 3), and that same conservatism is "
        "what keeps Medium/Hard-tier episodes off this list on the held-out "
        "set too — the detector is not missing them by accident, it is "
        "declining to flag anything it cannot flag confidently. A looser "
        "threshold would recover some of these at the cost of the "
        "zero-false-alarm property Phase 3 was built around; this table is "
        "the honest cost of that trade, not a bug to silently patch.",
        "",
        "## What this evaluation cannot tell you",
        "",
        "- **This is one held-out draw, not a distribution.** A single "
        "fresh seed tells you this detector's recall on *this* draw of "
        "episode timing and noise, not a confidence interval over many "
        "draws — treat the recall percentages above as one honest sample, "
        "not a guaranteed rate.",
        "- **The outcome model's success probabilities are stated "
        "assumptions, not measured ones** — see docs/OUTCOME-MODEL.md and "
        "docs/SENSITIVITY.md for the range the recovery figure moves "
        "across as those assumptions change.",
        "- **Agent-off recovers exactly Rs. 0.00 by construction**, since "
        "the generator does not model an independent, un-assisted retry "
        "behavior (docs/OUTCOME-MODEL.md §5) — the net incremental figure "
        "above is therefore equal to agent-on's own recovery minus cost, "
        "not a comparison against a competing baseline strategy.",
        "- **decoy-volume-spike's slice dimension (merchant category) is "
        "not one the lattice tests at any level**, so it cannot be scored "
        "as a false alarm or a correct non-detection either way — it is "
        "excluded from the decoy false-alarm count above rather than "
        "silently counted as a pass.",
    ]
    if not scorecard["escalation_reasons_count"] and not scorecard["hold_reasons_count"]:
        lines.append(
            "- **No guardrail fired in this run.** A real characteristic "
            "of this specific batch (moderate amounts, confidence above "
            "threshold, the detected incident's own aggregate never "
            "reached SEVERE), not a rendering gap — the zero counts above "
            "are genuine. See docs/JOURNAL.md."
        )

    return "\n".join(lines) + "\n"
